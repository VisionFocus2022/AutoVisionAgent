def set_language(lang: str) -> None:
    """切换当前语言（ch_CN / en_US）。"""
    global _LANG
    _LANG = lang


def current_language() -> str:
    return _LANG


def tr(text: str) -> str:
    """翻译包装：查当前语言字典，缺失则原样返回。"""
    if _LANG == "ch_CN":
        return text
    return _EN_US.get(text, text)


